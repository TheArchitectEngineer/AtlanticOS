def _chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind+data))


def render_png(lines, width=1000, height=760):
    bg, fg, accent = bytes((12, 22, 38)), bytes((207, 221, 232)), bytes((68, 218, 189))
    pixels = bytearray(bg * (width*height))
    wrapped = []
    for line in lines:
        wrapped.extend(textwrap.wrap(line, width=79, replace_whitespace=False) or [''])
    if len(wrapped) > 32:
        raise ValueError('UI exceeds framebuffer; do not silently clip')
    for row, line in enumerate(wrapped):
        color = accent if row == 0 or line.startswith('>') else fg
        for col, char in enumerate(line):
            for gy, glyph in enumerate(PATTERNS.get(char, PATTERNS['?']).split('/')):
                for gx, bit in enumerate(glyph):
                    if bit == '1':
                        x, y = 24+col*12+gx*2, 22+row*22+gy*2
                        for dy in (0, 1):
                            at = ((y+dy)*width+x)*3
                            pixels[at:at+6] = color*2
    scan = b''.join(b'\0'+pixels[y*width*3:(y+1)*width*3] for y in range(height))
    return (b'\x89PNG\r\n\x1a\n' + _chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0))
            + _chunk(b'IDAT', zlib.compress(scan, 9)) + _chunk(b'IEND', b''))
